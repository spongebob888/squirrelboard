import { test, expect } from 'playwright/test'

for (const storage of ['IndexedDB', 'memory']) {
  test(`category waterfall supports inspection, filters and frozen capture in ${storage}`, async ({ page }) => {
    await page.addInitScript(() => sessionStorage.setItem('squirrelboard.secret', 'fixture-secret'))
    if (storage === 'memory') await page.addInitScript(() => { window.Worker = class { constructor() { throw new Error('Fixture fallback') } } as any })
    let send: (text: string) => void = () => {}
    await page.routeWebSocket('**/api/v1/logs*', ws => { send = text => ws.send(text) })
    await page.goto('/#log')
    await page.addStyleTag({ content: '[id^="impeccable-live"] { visibility: hidden !important; pointer-events: none !important; }' })
    await expect(page.locator('.log-heading')).toContainText('Live')
    const events = ['proxy:accepted', 'routing:outbound_selected', 'dns:resolved', 'sniffer:protocol', 'security:checked', 'stream:closed', 'custom:event']
    const levels = ['INFO', 'DEBUG', 'WARN', 'ERROR', 'TRACE', 'INFO', 'INFO']
    const at = Date.now() - 5000
    const record = (index: number) => JSON.stringify({ timestamp: new Date(at + index * 500).toISOString(), level: levels[index % 7], target: 'shadowquic::test', event: events[index % 7], fields: { ...(index === 6 ? {} : { req_id: 42 + index }), message: `Waterfall event ${index}`, dst: 'waterfall.example:443' }, spans: [] })
    for (let index = 0; index < 7; index++) send(record(index))
    await page.getByRole('navigation', { name: 'Log views' }).getByRole('link', { name: 'Waterfall', exact: true }).click()
    await expect(page).toHaveURL(/view=waterfall/)
    await expect(page.locator('.waterfall-row')).toHaveCount(7)
    await expect(page.locator('.waterfall-dot')).toHaveCount(7)
    await expect(page.locator('.waterfall-label small')).toHaveText(Array(7).fill('1 event'))
    const colors = await page.locator('.waterfall-dot > span').evaluateAll(elements => elements.map(el => getComputedStyle(el).backgroundColor))
    expect(new Set(colors).size).toBe(7)
    const first = page.getByRole('button', { name: /proxy:accepted · Request 42/ })
    await first.focus()
    await page.keyboard.press('ArrowRight')
    const detail = page.getByRole('region', { name: 'Selected waterfall event' })
    await expect(detail).toContainText('Waterfall event 1')
    await expect(page.getByRole('button', { name: /routing:outbound_selected · Request 43/ })).toBeFocused()
    await page.keyboard.press('End')
    await expect(detail).toContainText('Unscoped event')
    await expect(detail.getByRole('button', { name: /View request/ })).toHaveCount(0)
    await first.click()
    await expect(detail).toContainText('Waterfall event 0')
    if (storage === 'IndexedDB') {
      await page.getByRole('button', { name: /dns:resolved · Request 44/ }).click()
      await expect(detail.locator('.waterfall-level')).toHaveCSS('color', 'rgb(195, 145, 69)')
      await page.getByRole('button', { name: /sniffer:protocol · Request 45/ }).click()
      await expect(detail.locator('.waterfall-level')).toHaveCSS('color', 'rgb(212, 92, 101)')
      await page.screenshot({ path: '.impeccable/review/log-waterfall-desktop.png', fullPage: true, animations: 'disabled' })
      await page.evaluate(() => document.documentElement.dataset.theme = 'dark')
      await expect(detail.locator('.waterfall-level')).toHaveCSS('color', 'rgb(237, 148, 154)')
      await page.screenshot({ path: '.impeccable/review/log-waterfall-dark.png', fullPage: true, animations: 'disabled' })
      await page.setViewportSize({ width: 390, height: 1000 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      expect(await page.locator('.waterfall-scroll').evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true)
      await page.screenshot({ path: '.impeccable/review/log-waterfall-mobile.png', fullPage: true, animations: 'disabled' })
      await page.setViewportSize({ width: 1440, height: 1000 })
    }
    const eventLimit = page.getByRole('spinbutton', { name: 'Events per page', exact: true })
    await eventLimit.fill('3')
    await eventLimit.press('Enter')
    await expect(page.locator('.waterfall-dot')).toHaveCount(3)
    const axisTimes = page.locator('.waterfall-scale time')
    await expect(axisTimes.first()).toHaveAttribute('datetime', new Date(at).toISOString())
    await expect(axisTimes.last()).toHaveAttribute('datetime', new Date(at + 1000).toISOString())
    const scale = (await page.locator('.waterfall-scale').boundingBox())!
    const minimum = (await first.boundingBox())!
    const maximum = (await page.getByRole('button', { name: /dns:resolved · Request 44/ }).boundingBox())!
    expect(minimum.x + minimum.width / 2).toBeCloseTo(scale.x, 0)
    expect(maximum.x + maximum.width / 2).toBeCloseTo(scale.x + scale.width, 0)
    await page.getByRole('button', { name: 'Next events', exact: true }).click()
    await expect(axisTimes.first()).toHaveAttribute('datetime', new Date(at + 1500).toISOString())
    await expect(axisTimes.last()).toHaveAttribute('datetime', new Date(at + 2500).toISOString())
    await eventLimit.fill('500')
    await eventLimit.press('Enter')
    await expect(page.locator('.waterfall-dot')).toHaveCount(7)
    await page.getByRole('button', { name: 'Freeze view', exact: true }).click()
    send(record(7))
    await expect(page.locator('.log-help-summary')).toContainText('8')
    await expect(page.locator('.waterfall-dot')).toHaveCount(7)
    await page.getByRole('button', { name: 'Follow live', exact: true }).click()
    await expect(page.locator('.waterfall-dot')).toHaveCount(8)
    await page.getByRole('combobox', { name: 'Log level', exact: true }).selectOption('INFO')
    await expect(page.locator('.waterfall-dot')).toHaveCount(6)
    await first.click()
    await expect(detail).toContainText('Waterfall event 0')
    await detail.getByRole('button', { name: 'View request 42 timeline', exact: true }).click()
    await expect(page.locator('.log-timeline-heading h3')).toHaveText('Request 42')
    await expect(page.getByRole('link', { name: 'Request timelines', exact: true })).toHaveAttribute('aria-current', 'page')
    await page.getByRole('link', { name: 'Waterfall', exact: true }).click()
    await page.reload()
    await expect(page.getByRole('link', { name: 'Waterfall', exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(page.getByLabel('Request ID', { exact: true })).toHaveValue('42')
  })
}

test('waterfall pages every matching point and loads only the selected body', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('squirrelboard.secret', 'fixture-secret'))
  await page.routeWebSocket('**/api/v1/logs*', () => {})
  await page.goto('/#log?view=waterfall')
  const result = await page.evaluate(async () => {
    const path = '/src/lib/log-storage.ts'
    const { LogDatabase } = await import(path)
    const db = new LogDatabase(); await db.open()
    const now = Date.now()
    const events = Array.from({ length: 1001 }, (_, index) => ({ sequence: 0, receivedAt: now - 1000 + index, at: now - 1000 + index, timestamp: new Date(now - 1000 + index).toISOString(), level: ['TRACE', 'INFO', 'ERROR'][index % 3], target: 'test', event: index % 2 ? 'dns:resolved' : 'proxy:accepted', fields: { message: `Point ${index}` }, spans: [], requestId: String(index % 31) }))
    await db.append(location.origin, events, 5000, now)
    const options = { mode: 'waterfall', end: now, windowMs: 60_000, requestId: '', page: 1, limit: 500 }
    const pages = await Promise.all([0, 500, 1000].map(offset => db.query(location.origin, { ...options, offset })))
    const selected = await db.query(location.origin, { ...options, eventSequence: pages[2].waterfall.points[0].sequence })
    const filtered = await db.query(location.origin, { ...options, level: 'WARN', offset: 1000 })
    db.close()
    return {
      sizes: pages.map(view => view.waterfall.points.length), unique: new Set(pages.flatMap(view => view.waterfall.points.map((point: any) => point.sequence))).size,
      ranges: pages.map(view => [view.waterfall.start, view.waterfall.end]), fits: pages.every(view => view.waterfall.start === view.waterfall.points[0].at && view.waterfall.end === view.waterfall.points.at(-1).at), bodies: pages.map(view => view.events.length),
      selected: selected.events.map((event: any) => event.fields.message), count: selected.waterfall.total,
      filtered: { total: filtered.waterfall.total, offset: filtered.waterfall.offset, levels: [...new Set(filtered.waterfall.points.map((point: any) => point.level))] },
    }
  })
  expect(result.sizes).toEqual([500, 500, 1])
  expect(result.unique).toBe(1001)
  expect(result.bodies).toEqual([0, 0, 0])
  expect(result.fits).toBe(true)
  expect(result.ranges[0]![1]).toBeLessThan(result.ranges[1]![0]!)
  expect(result.ranges[1]![1]).toBeLessThan(result.ranges[2]![0]!)
  expect(result.selected).toEqual(['Point 1000'])
  expect(result.count).toBe(1001)
  expect(result.filtered).toEqual({ total: 333, offset: 0, levels: ['ERROR'] })
  await expect(page.locator('.waterfall-dot')).toHaveCount(500)
  await page.getByRole('button', { name: 'Freeze view', exact: true }).click()
  await page.getByRole('button', { name: 'Next events', exact: true }).click()
  await expect(page.locator('.waterfall-pagination')).toContainText('501–1000')
  await page.getByRole('button', { name: 'Next events', exact: true }).click()
  await expect(page.locator('.waterfall-dot')).toHaveCount(1)
  await expect(page.locator('.waterfall-pagination')).toContainText('1001–1001')
  await page.getByRole('combobox', { name: 'Log level', exact: true }).selectOption('WARN')
  await expect(page.locator('.waterfall-dot')).toHaveCount(333)
  await expect(page.locator('.waterfall-heading')).toContainText('333 events')
  await expect(page.locator('.waterfall-pagination')).toHaveCount(0)
  const eventLimit = page.getByRole('spinbutton', { name: 'Events per page', exact: true })
  await eventLimit.fill('200')
  await eventLimit.press('Enter')
  await expect(page.locator('.waterfall-dot')).toHaveCount(200)
  await expect(page.locator('.waterfall-pagination')).toContainText('1–200')
  await page.getByRole('button', { name: 'Next events', exact: true }).click()
  await expect(page.locator('.waterfall-dot')).toHaveCount(133)
  await expect(page.locator('.waterfall-pagination')).toContainText('201–333')
  expect(await page.evaluate(() => localStorage.getItem('squirrelboard.waterfallLimit'))).toBe('200')
  await page.reload()
  await expect(eventLimit).toHaveValue('200')
  await expect(page.locator('.waterfall-dot')).toHaveCount(200)
  await eventLimit.fill('20000')
  await eventLimit.press('Enter')
  expect(await eventLimit.evaluate((input: HTMLInputElement) => input.validity.valid)).toBe(false)
  await expect(page.locator('.waterfall-dot')).toHaveCount(200)
})

for (const width of [1440, 390]) {
  test.describe(`coincident dots at ${width}px`, () => {
    test.use({ viewport: { width, height: 1000 }, hasTouch: width < 740 })
    test('coincident dots keep one compact row and remain keyboard accessible', async ({ page }) => {
      await page.addInitScript(() => sessionStorage.setItem('squirrelboard.secret', 'fixture-secret'))
      await page.routeWebSocket('**/api/v1/logs*', ws => {
        const timestamp = new Date().toISOString()
        for (let index = 0; index < 12; index++) ws.send(JSON.stringify({ timestamp, level: 'INFO', target: 'test', event: 'proxy:accepted', fields: { req_id: 42, message: `Coincident event ${index}` }, spans: [] }))
      })
      await page.goto('/#log?view=waterfall')
      await page.addStyleTag({ content: '[id^="impeccable-live"] { visibility: hidden !important; pointer-events: none !important; }' })
      await expect(page.locator('.waterfall-dot')).toHaveCount(12)
      const dots = page.locator('.waterfall-dot')
      const positions = await dots.evaluateAll(elements => elements.map(el => { const box = el.getBoundingClientRect(); return { x: box.x, y: box.y, bottom: box.bottom } }))
      expect(new Set(positions.map(box => box.x)).size).toBe(1)
      expect(new Set(positions.map(box => box.y)).size).toBe(1)
      expect((await page.getByRole('group', { name: 'Connection: 12 events' }).boundingBox())!.height).toBeLessThanOrEqual(48)
      if (width < 740) await dots.last().tap()
      else await dots.last().click()
      const detail = page.getByRole('region', { name: 'Selected waterfall event' })
      await expect(detail).toContainText('Coincident event 11')
      await page.keyboard.press('Home')
      await expect(detail).toContainText('Coincident event 0')
      for (let index = 0; index < 5; index++) await page.keyboard.press('ArrowRight')
      await expect(detail).toContainText('Coincident event 5')
      await page.keyboard.press('End')
      await expect(detail).toContainText('Coincident event 11')
      await page.locator('.waterfall-scroll').evaluate(el => el.scrollTop = 0)
      await page.evaluate(() => window.scrollTo(0, 0))
      if (width < 740) await page.evaluate(() => document.documentElement.dataset.theme = 'dark')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.screenshot({ path: `.impeccable/review/log-waterfall-dense-${width}.png`, fullPage: true, animations: 'disabled' })
    })
  })
}
