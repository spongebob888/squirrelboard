import { test, expect } from 'playwright/test'

for (const width of [1440, 390]) {
  test(`incoming requests preserve the selected event reading position at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.addInitScript(() => {
      localStorage.setItem('squirrelboard.backend', JSON.stringify({ name: 'Fixture', url: '', interval: 1000 }))
      sessionStorage.setItem('squirrelboard.secret', 'fixture-secret')
    })
    let send: (text: string) => void = () => {}
    await page.routeWebSocket('**/api/v1/logs*', ws => { send = text => ws.send(text) })
    await page.goto('/#log')
    await expect(page.locator('.log-heading')).toContainText('Live')
    const record = (id: number, index: number) => JSON.stringify({ timestamp: new Date(Date.now() + index).toISOString(), level: 'INFO', target: 'shadowquic::test', event: 'proxy:request_accepted', fields: { req_id: id, message: `Event ${index}`, dst: 'example.com:443' }, spans: [] })
    for (let index = 0; index < 60; index++) send(record(42, index))
    await expect(page.locator('.log-events li')).toHaveCount(60)
    for (let index = 0; index < 10; index++) send(record(200 + index, index))
    await expect(page.locator('.log-list-heading')).toContainText('11 requests')
    await page.getByRole('button', { name: /Request 42 / }).click()
    const event = page.locator('.log-events li').nth(8)
    await event.scrollIntoViewIfNeeded()
    const before = await event.boundingBox()
    for (let index = 0; index < 8; index++) send(record(100 + index, index))
    await expect(page.locator('.log-list-heading')).toContainText('19 requests')
    await expect(page.locator('.log-timeline-heading h3')).toHaveText('Request 42')
    await expect.poll(async () => (await event.boundingBox())!.y).toBeCloseTo(before!.y, 0)
    expect(await page.locator('.log-requests').evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
    for (let index = 0; index < 35; index++) send(record(300 + index, index))
    await expect(page.locator('.log-list-heading')).toContainText('54 requests')
    await expect.poll(async () => (await event.boundingBox())!.y).toBeCloseTo(before!.y, 0)
    // The selected request has moved off the first request page; its timeline stays open.
    await expect(page.locator('.log-events li')).toHaveCount(60)
    await page.screenshot({ path: `.impeccable/review/log-scroll-${width}.png`, animations: 'disabled' })
  })
}

test('an explicitly selected request never switches to a new request when it leaves the window', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('squirrelboard.secret', 'fixture-secret'))
  await page.routeWebSocket('**/api/v1/logs*', () => {})
  await page.goto('/#log')
  await page.evaluate(async () => {
    const path = '/src/lib/log-storage.ts'
    const { LogDatabase } = await import(path)
    const db = new LogDatabase()
    await db.open()
    const now = Date.now()
    const event = (id: string | null, age: number) => ({ sequence: 0, receivedAt: now - age, at: now - age, timestamp: new Date(now - age).toISOString(), level: 'INFO', target: 'shadowquic::test', event: 'proxy:request_accepted', fields: { message: `Request ${id} event` }, spans: [], requestId: id })
    await db.append(location.origin, [event('42', 120_000), event(null, 90_000), event('43', 100)], 100_000, now)
    db.close()
  })
  const request = page.getByRole('button', { name: /Request 42 / })
  await expect(request).toBeVisible()
  await request.focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('.log-timeline-heading h3')).toHaveText('Request 42')
  await expect(request).toBeFocused()
  await page.getByLabel('Time window').selectOption('60000')
  await expect(page.getByRole('heading', { name: 'Request 42 is no longer in this window' })).toBeVisible()
  await expect(page.locator('.log-events li')).toHaveCount(0)
  await page.getByRole('button', { name: 'Show newest request', exact: true }).click()
  await expect(page.locator('.log-timeline-heading h3')).toHaveText('Request 43')
  await page.getByRole('button', { name: 'Freeze view', exact: true }).click()
  await page.getByLabel('Time window').selectOption('300000')
  await page.getByRole('button', { name: /Unscoped events/ }).click()
  await expect(page.locator('.log-timeline-heading h3')).toHaveText('Unscoped events')
  await page.getByLabel('Time window').selectOption('60000')
  await expect(page.getByRole('heading', { name: 'Unscoped events are no longer in this window' })).toBeVisible()
  await expect(page.locator('.log-events li')).toHaveCount(0)
  await page.getByRole('button', { name: 'Show newest request', exact: true }).click()
  await expect(page.locator('.log-timeline-heading h3')).toHaveText('Request 43')
})
